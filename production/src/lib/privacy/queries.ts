/**
 * R-2013: Settings → Privacy requests, the browser side. Everything runs as the signed-in
 * user: RLS shows only confirmed requests of their own company to the owner / a manager, and
 * the actions go through privacy_request_action (owner/manager only, logged in activity_log).
 */
"use client";

import { useQuery, useMutation, useQueryClient } from "@tanstack/react-query";
import { createClient } from "@/lib/supabase/client";
import { toastError } from "@/lib/errors/toast-error";
import { logExport, countJsonRows } from "@/lib/export-log";
import { buildCSV } from "@/lib/csv";
import {
  PRIVACY_REQUEST_COLUMNS, exportCsvRows, exportFileStem, sortRequests,
  type PersonExport, type PrivacyRequestRow,
} from "./requests";

const KEY = ["privacy_requests"] as const;

/* privacy_requests is newer than database.generated.ts (shared, regenerated by its owner). */
type Loose = { from: (t: string) => any; rpc: (fn: string, args: Record<string, unknown>) => any }; // eslint-disable-line @typescript-eslint/no-explicit-any
const db = () => createClient() as unknown as Loose;

export function usePrivacyRequests() {
  return useQuery({
    queryKey: KEY,
    queryFn: async (): Promise<PrivacyRequestRow[]> => {
      const { data, error } = await db().from("privacy_requests")
        .select(PRIVACY_REQUEST_COLUMNS)
        .order("due_by", { ascending: true })
        .limit(500);
      if (error) throw new Error(error.message);
      return sortRequests((data ?? []) as PrivacyRequestRow[]);
    },
  });
}

export function usePrivacyAction() {
  const qc = useQueryClient();
  return useMutation({
    mutationFn: async (v: { id: string; action: "exported" | "corrected" | "closed"; note?: string }) => {
      const { error } = await db().rpc("privacy_request_action", { p_id: v.id, p_action: v.action, p_note: v.note ?? null });
      if (error) throw new Error(error.message);
    },
    onSuccess: () => { qc.invalidateQueries({ queryKey: KEY }); },
    onError: (err) => toastError(err),
  });
}

const LEAD_COLS = "id, company, contact_name, contact_email, contact_phone, plan, seats, stage, source, notes, domain, gstin, state, country, requirement, created_at, updated_at";
const CUSTOMER_COLS = "id, name, display_name, contact_name, contact_first_name, contact_last_name, contact_email, contact_phone, contact_mobile, contact_persons, gstin, pan, address, city, state, pin_code, country, shipping_address, created_at, updated_at";
const CONSENT_COLS = "id, lead_id, purpose, choice, notice_version, source, form, page, created_at";
const INVOICE_COLS = "id, invoice_date, amount, status, customer_name, customer_gstin, billing_address";

/** Everything the company holds about this person: their leads, customers, consent records, invoices. */
export async function loadPersonExport(r: PrivacyRequestRow): Promise<PersonExport> {
  const c = db();
  const none = { data: [], error: null };
  const [leads, customers, consent, invoices] = await Promise.all([
    r.lead_ids.length ? c.from("leads").select(LEAD_COLS).in("id", r.lead_ids) : none,
    r.customer_ids.length ? c.from("customers").select(CUSTOMER_COLS).in("id", r.customer_ids) : none,
    r.lead_ids.length ? c.from("consent_events").select(CONSENT_COLS).in("lead_id", r.lead_ids).order("created_at") : none,
    r.customer_ids.length ? c.from("invoices").select(INVOICE_COLS).in("customer_id", r.customer_ids).order("invoice_date").limit(1000) : none,
  ]);
  for (const res of [leads, customers, consent, invoices]) if (res.error) throw new Error(res.error.message);
  return {
    request: { id: r.id, kind: r.kind, name: r.full_name, email: r.email, phone: r.phone, confirmed: r.verified_at, due_by: r.due_by },
    leads: leads.data ?? [], customers: customers.data ?? [], consent: consent.data ?? [], invoices: invoices.data ?? [],
  };
}

function hand(name: string, blob: Blob) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

/** Download the person's data as JSON or CSV; logged in export_log and on the request. */
export async function downloadPersonExport(r: PrivacyRequestRow, format: "json" | "csv"): Promise<void> {
  const data = await loadPersonExport(r);
  const stem = exportFileStem(r.full_name);
  if (format === "json") {
    hand(`${stem}.json`, new Blob([JSON.stringify(data, null, 2)], { type: "application/json" }));
    void logExport({ what: "privacy-request-export", rowCount: countJsonRows(data), format: "json" });
  } else {
    const { headers, rows } = exportCsvRows(data);
    hand(`${stem}.csv`, new Blob(["﻿", buildCSV(headers, rows)], { type: "text/csv;charset=utf-8" }));
    void logExport({ what: "privacy-request-export", rowCount: rows.length, format: "csv" });
  }
}
