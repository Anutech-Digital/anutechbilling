/**
 * R-2350 (G-DPDP) — record that someone opened a customer's or a lead's detail.
 *
 * WHY: only exports were logged (R-1006). Nobody could tell who LOOKED at a person's data.
 * The customer profile (page + the /customers side pane) and the lead drawer call
 * `useRecordView` once when they open a record. It calls the database function
 * `log_record_view()`, which takes the company and the user from the session — never from the
 * browser — checks the record is the caller's own company's, and writes at most one row per
 * user + record per 10 minutes. The owner reads them in Settings → Security log.
 *
 * CHEAP: one small call per detail OPEN — never on a list render. The browser also remembers
 * what it logged in the last 10 minutes, so re-opening the same drawer sends nothing.
 *
 * THE ONE RULE (same as export-log): logging never stops the screen. `logRecordView` never
 * throws and never rejects; a failure is a console warning.
 */
"use client";

import * as React from "react";

export type AccessRecordType = "customer" | "lead";

/** Same window as the database's debounce in log_record_view(). */
export const RECORD_VIEW_WINDOW_MS = 10 * 60 * 1000;

type RpcResult = { error: { message?: string } | null };
export type RecordViewWriter = (args: { p_record_type: AccessRecordType; p_record_id: string }) => PromiseLike<RpcResult>;

/** key → when this browser last sent it. Module-level: one per tab. */
const sentAt = new Map<string, number>();

/** Test hook: forget what was sent. */
export function resetRecordViewMemory(): void {
  sentAt.clear();
}

async function defaultWriter(args: Parameters<RecordViewWriter>[0]): Promise<RpcResult> {
  const { createClient } = await import("@/lib/supabase/client");
  /* log_record_view is newer than database.generated.ts (shared, regenerated by its owner). */
  const db = createClient() as unknown as { rpc: (fn: string, a: Record<string, unknown>) => PromiseLike<RpcResult> };
  return await db.rpc("log_record_view", args);
}

/**
 * Write one access-log row (the database may still skip it inside its 10-minute window).
 * Returns true when a call was sent. Never throws, never rejects.
 */
export async function logRecordView(
  recordType: AccessRecordType,
  recordId: string | null | undefined,
  writer: RecordViewWriter = defaultWriter,
  now: number = Date.now(),
): Promise<boolean> {
  const id = (recordId ?? "").trim();
  if (!id) return false;
  const key = `${recordType}:${id}`;
  const last = sentAt.get(key);
  if (last != null && now - last < RECORD_VIEW_WINDOW_MS) return false;
  sentAt.set(key, now);
  try {
    const { error } = await writer({ p_record_type: recordType, p_record_id: id });
    if (error) console.warn(`[security-log] could not record ${recordType} view: ${error.message ?? "unknown error"}`);
  } catch (e) {
    console.warn(`[security-log] could not record ${recordType} view: ${e instanceof Error ? e.message : String(e)}`);
  }
  return true;
}

/**
 * Log one open of this record's detail. Call it in the detail component, with the id of the
 * record on screen (null while nothing is open). Runs once per record id.
 */
export function useRecordView(recordType: AccessRecordType, recordId: string | null | undefined, writer?: RecordViewWriter): void {
  React.useEffect(() => {
    if (!recordId) return;
    void logRecordView(recordType, recordId, writer);
  }, [recordType, recordId, writer]);
}
