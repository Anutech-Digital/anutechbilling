/**
 * Generates prisma/migrations/20261005120000_tenant_context/migration.sql from a database
 * built out of git (`npm run db:local`). Run once; the output is committed and reviewed.
 *
 *   MIGRATE_DATABASE_URL=postgresql://postgres:localdev@localhost:54329/ros node scripts/gen-tenant-context-migration.mjs
 *
 * WHAT IT DOES — makes every policy and function work for BOTH ways into the database:
 *   • PostgREST (today): identity comes from the verified Supabase JWT → auth.uid()/auth.role().
 *   • Prisma (new):      identity comes from set_config('app.user_id'/'app.tenant_id', …, true)
 *                        set by src/server/db/withTenant inside one transaction.
 * The helper picks by session_user — the LOGIN role, which a SECURITY DEFINER function does
 * not change (current_user would become the function owner). PostgREST logs in as
 * `authenticator`, so on that path the app.* settings are ignored entirely.
 *
 * Every policy / function that says auth.uid() or auth.role() is rewritten to the helper.
 * Bodies are copied from the catalog (pg_get_functiondef, pg_policies) and only those two
 * tokens change, so the money logic itself is untouched — see the diff check at the end.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import pg from "pg";

const url = process.env.MIGRATE_DATABASE_URL;
if (!url || !/localhost|127\.0\.0\.1/.test(url)) {
  console.error("MIGRATE_DATABASE_URL must point at the LOCAL database built from git.");
  process.exit(1);
}
const db = new pg.Client({ connectionString: url });
await db.connect();

const HELPERS = new Set(["current_user_id", "current_request_role", "current_tenant_id"]);
const swap = (s) => s.replace(/\bauth\.uid\(\)/g, "public.current_user_id()").replace(/\bauth\.role\(\)/g, "public.current_request_role()");
const ident = (s) => '"' + s.replace(/"/g, '""') + '"';

const policies = (await db.query(`
  select schemaname, tablename, policyname, qual, with_check
    from pg_policies
   where coalesce(qual,'') || coalesce(with_check,'') ~ 'auth\\.(uid|role)\\(\\)'
   order by schemaname, tablename, policyname`)).rows;

const functions = (await db.query(`
  select p.oid, n.nspname, p.proname, pg_get_functiondef(p.oid) as def
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname in ('public', 'storage')
     and p.prokind = 'f'
     and p.prosrc ~ 'auth\\.(uid|role)\\(\\)'
   order by n.nspname, p.proname, p.oid`)).rows.filter((f) => !HELPERS.has(f.proname));

await db.end();

const out = [];
out.push(`-- Tenant context for the Prisma path — GENERATED by scripts/gen-tenant-context-migration.mjs
-- from the schema built out of git (supabase/baseline.sql + supabase/migrations up to
-- 20261005100000). Review the helpers by hand; the rewrites below change ONLY the tokens
-- auth.uid() → public.current_user_id() and auth.role() → public.current_request_role().
--
-- Rewrites: ${policies.length} policies, ${functions.length} functions.
--
-- PREREQUISITE (once per database, as an admin — not part of this migration because it
-- needs CREATEROLE and a password): db/ops/10-runtime-roles.sql creates app_runtime and
-- app_jobs. This migration does not depend on them existing.

-- ─── 1. Helpers ─────────────────────────────────────────────────────────────

-- One transaction: Prisma Migrate does not add one, and a half-applied rewrite of the
-- money functions is the one outcome this migration must never have.
begin;

-- Who is calling. Prisma path: the user id withTenant() set for THIS transaction.
-- PostgREST path: the verified JWT, exactly as before. Missing setting → NULL → no rows.
create or replace function public.current_user_id() returns uuid
  language sql stable set search_path = ''
as $$
  select case
    when session_user in ('app_runtime', 'app_jobs')
      then nullif(current_setting('app.user_id', true), '')::uuid
    else auth.uid()
  end;
$$;

-- Which kind of caller. The Prisma path can NEVER claim 'service_role': the 20 policies and
-- 23 functions that trust auth.role() = 'service_role' read a setting (request.jwt.claims)
-- that code holding a connection could set itself. Here it is fixed by the login role.
create or replace function public.current_request_role() returns text
  language sql stable set search_path = ''
as $$
  select case session_user
    when 'app_runtime' then 'authenticated'
    when 'app_jobs'    then 'app_jobs'
    else auth.role()
  end;
$$;

-- The tenant. Same name and signature as before (365 references keep working).
-- Prisma path, app_runtime: the tenant is only accepted if the user id belongs to it —
-- code that passes the wrong tenant for a user gets NULL (no rows), not the other tenant.
-- app_jobs may act for a tenant without a user (background work); it still sees one tenant.
create or replace function public.current_tenant_id() returns uuid
  language sql stable security definer set search_path = ''
as $$
  select case
    when session_user = 'app_runtime' then (
      select u.tenant_id from public.users u
       where u.id = nullif(current_setting('app.user_id', true), '')::uuid
         and u.tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid
       limit 1)
    when session_user = 'app_jobs' then
      case when nullif(current_setting('app.user_id', true), '') is null
        then nullif(current_setting('app.tenant_id', true), '')::uuid
        else (select u.tenant_id from public.users u
               where u.id = nullif(current_setting('app.user_id', true), '')::uuid
                 and u.tenant_id = nullif(current_setting('app.tenant_id', true), '')::uuid
               limit 1)
      end
    else (select tenant_id from public.users where id = auth.uid() limit 1)
  end;
$$;

grant execute on function public.current_user_id(), public.current_request_role(), public.current_tenant_id()
  to anon, authenticated, service_role;
`);

out.push(`-- ─── 2. Policies (${policies.length}) ─────────────────────────────────────────────`);
for (const p of policies) {
  const parts = [];
  if (p.qual) parts.push(`using (${swap(p.qual)})`);
  if (p.with_check) parts.push(`with check (${swap(p.with_check)})`);
  out.push(`alter policy ${ident(p.policyname)} on ${ident(p.schemaname)}.${ident(p.tablename)}\n  ${parts.join("\n  ")};`);
}

out.push(`\n-- ─── 3. Functions (${functions.length}) ──────────────────────────────────────────`);
for (const f of functions) {
  out.push(`-- ${f.nspname}.${f.proname}\n${swap(f.def).trimEnd()};\n`);
}

out.push(`-- ─── 4. Nothing may still read the JWT directly ─────────────────────────────
do $$
declare n int;
begin
  select count(*) into n from pg_policies
   where coalesce(qual,'') || coalesce(with_check,'') ~ 'auth\\.(uid|role)\\(\\)';
  if n > 0 then raise exception 'tenant_context: % policies still use auth.uid()/auth.role()', n; end if;

  select count(*) into n from pg_proc p join pg_namespace s on s.oid = p.pronamespace
   where s.nspname in ('public','storage') and p.prosrc ~ 'auth\\.(uid|role)\\(\\)'
     and p.proname not in ('current_user_id','current_request_role','current_tenant_id');
  if n > 0 then raise exception 'tenant_context: % functions still use auth.uid()/auth.role()', n; end if;
end $$;

commit;
`);

const dir = "prisma/migrations/20261005120000_tenant_context";
mkdirSync(dir, { recursive: true });
writeFileSync(`${dir}/migration.sql`, out.join("\n"));
console.log(`wrote ${dir}/migration.sql — ${policies.length} policies, ${functions.length} functions`);
